  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  sent_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_channel_messages_conversation_direction_external (conversation_id, direction, external_message_id),
  KEY idx_channel_messages_conversation_created (conversation_id, created_at),
  KEY idx_channel_messages_status_created (status, created_at),
  CONSTRAINT fk_channel_messages_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
  CONSTRAINT fk_channel_messages_account FOREIGN KEY (account_id) REFERENCES channel_accounts(id),
  CONSTRAINT fk_channel_messages_conversation FOREIGN KEY (conversation_id) REFERENCES channel_conversations(id),
  CONSTRAINT fk_channel_messages_run FOREIGN KEY (run_id) REFERENCES channel_runs(id),
  CONSTRAINT fk_channel_messages_internal FOREIGN KEY (internal_message_id) REFERENCES tenant_session_messages(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS channel_outbox (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id BIGINT UNSIGNED NOT NULL,
  account_id BIGINT UNSIGNED NOT NULL,
  conversation_id BIGINT UNSIGNED NOT NULL,
  run_id CHAR(36) NULL,
  message_id BIGINT UNSIGNED NOT NULL,
  operation VARCHAR(16) NOT NULL,
  sequence_no INT UNSIGNED NOT NULL DEFAULT 0,
  chunk_count INT UNSIGNED NOT NULL DEFAULT 1,
  idempotency_key VARCHAR(255) NOT NULL,
  payload_json JSON NOT NULL,
  render_sha256 BINARY(32) NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  attempts INT UNSIGNED NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  retry_after_ms INT UNSIGNED NULL,
  lease_owner VARCHAR(255) NULL,
  lease_until DATETIME(3) NULL,
  last_error_code VARCHAR(128) NULL,
  last_error_message VARCHAR(1024) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  sent_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_channel_outbox_delivery (account_id, idempotency_key, sequence_no, operation),
  CHECK (status IN ('pending', 'sending', 'sent', 'retry', 'delivery_unknown', 'dead')),
  KEY idx_channel_outbox_status_next_attempt (status, next_attempt_at),
  KEY idx_channel_outbox_account_status (account_id, status),
  KEY idx_channel_outbox_conversation_created (conversation_id, created_at),
  CONSTRAINT fk_channel_outbox_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
  CONSTRAINT fk_channel_outbox_account FOREIGN KEY (account_id) REFERENCES channel_accounts(id),
  CONSTRAINT fk_channel_outbox_conversation FOREIGN KEY (conversation_id) REFERENCES channel_conversations(id),
  CONSTRAINT fk_channel_outbox_run FOREIGN KEY (run_id) REFERENCES channel_runs(id),
  CONSTRAINT fk_channel_outbox_message FOREIGN KEY (message_id) REFERENCES channel_messages(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

