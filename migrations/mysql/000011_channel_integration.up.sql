SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS channel_accounts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id BIGINT UNSIGNED NOT NULL,
  provider VARCHAR(32) NOT NULL,
  account_key VARCHAR(128) NOT NULL,
  app_id VARCHAR(255) NOT NULL,
  credential_ref VARCHAR(512) NOT NULL,
  mode VARCHAR(16) NOT NULL,
  enabled TINYINT(1) NOT NULL DEFAULT 0,
  policy_json JSON NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'disabled',
  last_connected_at DATETIME(3) NULL,
  last_error_code VARCHAR(128) NULL,
  last_error_message VARCHAR(1024) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  archived_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_channel_accounts_tenant_provider_key (tenant_id, provider, account_key),
  KEY idx_channel_accounts_tenant_enabled_provider (tenant_id, enabled, provider),
  CONSTRAINT fk_channel_accounts_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS channel_identities (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
