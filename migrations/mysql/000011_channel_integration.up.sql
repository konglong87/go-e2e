  archived_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_channel_identities_account_external_user (account_id, external_user_id),
  KEY idx_channel_identities_tenant_user (tenant_id, user_id),
  CONSTRAINT fk_channel_identities_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
  CONSTRAINT fk_channel_identities_account FOREIGN KEY (account_id) REFERENCES channel_accounts(id),
  CONSTRAINT fk_channel_identities_user FOREIGN KEY (user_id) REFERENCES tenant_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

