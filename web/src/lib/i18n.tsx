const I18nContext = createContext<I18nContextValue | null>(null);

export function webUIV2TranslationKeys(language: Language): string[] {
  return Object.entries(translations[language])
    .filter(([key, value]) => key.startsWith("webui2.") && value.trim() !== "")
    .map(([key]) => key)
    .sort();
}

export function webUIV2Translations(language: Language): Readonly<Record<string, string>> {
  return Object.fromEntries(Object.entries(translations[language]).filter(([key]) => key.startsWith("webui2.")));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => loadLanguage());
  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        setLanguageState(nextLanguage);
        window.localStorage.setItem(languageStorageKey, nextLanguage);
      },
      t: (key, params) => formatTranslation(translations[language][key] || translations.en[key] || key, params)
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}

function loadLanguage(): Language {
  try {
	    const raw = readProductStorage(languageStorageKey);
    return raw === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}

function formatTranslation(template: string, params?: TranslationParams): string {
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce((current, [key, value]) => current.replaceAll(`{${key}}`, String(value)), template);
}
